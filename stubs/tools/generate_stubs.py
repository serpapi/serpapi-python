#!/usr/bin/env python3
"""Generate serpapi-stubs engine-specific stubs from the normalized engine snapshot."""

from __future__ import annotations

import argparse
import ast
import json
import keyword
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

STUBS_ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT_PATH = STUBS_ROOT / "data" / "engines.json"
OUTPUT_DIR = STUBS_ROOT / "serpapi-stubs"
GENERATED_FILES = ("core.pyi", "engine_params.pyi")
REQUEST_OPTIONS = (
    ("cert", "_Cert"),
    ("proxies", "_Proxies"),
    ("stream", "Optional[bool]"),
    ("timeout", "_Timeout"),
    ("verify", "_Verify"),
)
REQUEST_OPTION_NAMES = frozenset(name for name, _ in REQUEST_OPTIONS)
NUMERIC_PARAM_NAMES = frozenset({"limit", "num", "offset", "page", "start"})
BOOLEAN_PARAM_NAMES = frozenset({"async", "include_filters", "no_cache", "zero_trace"})
RESERVED_KEYWORD_NAMES = frozenset({"params", "self"})
# Playground "required" flags are often conditional (for example, google_lens `url` can be replaced by
# `image_id`), so the snapshot does not keep them; only parameters the API cannot work without are required.
REQUIRED_PARAMS = {"extract": frozenset({"url"})}
# SerpApi runs Google when `engine` is omitted, so only Google calls may leave it out.
DEFAULT_ENGINE = "google"
JSON_OUTPUT = 'Literal["json"]'
TEXT_OUTPUT = 'Literal["html", "md"]'
FALLBACK_RETURN = "Union[SerpResults, Any]"
# search(), search_archive(), locations() and account() write the API key and keyword parameters into the
# mapping they are given, so a read-only Mapping fails at runtime; extract() copies it. TypedDicts are not
# MutableMapping, so the fallback overloads list the engine types next to it.
MUTABLE_PARAMS = "MutableMapping[str, Any]"
HEADER = (
    "# Generated by stubs/tools/generate_stubs.py from stubs/data/engines.json.\n"
    "# Do not edit by hand; run `python stubs/tools/generate_stubs.py` instead.\n"
)


@dataclass(frozen=True)
class Param:
    name: str
    typ: str
    required: bool


ARCHIVE_PARAMS = (Param("api_key", "str", False), Param("search_id", "str", True))


@dataclass(frozen=True)
class Engine:
    name: str
    class_prefix: str
    params: tuple[Param, ...]
    engine_required: bool

    @property
    def json_params(self) -> str:
        return f"{self.class_prefix}JsonSearchParams"

    @property
    def text_params(self) -> str:
        return f"{self.class_prefix}TextSearchParams"

    @property
    def search_params(self) -> str:
        return f"{self.class_prefix}SearchParams"


def class_prefix(engine: str) -> str:
    return "".join(part[:1].upper() + part[1:] for part in re.split(r"[^0-9A-Za-z]+", engine) if part)


def is_keyword_argument(name: str) -> bool:
    return name.isidentifier() and not keyword.iskeyword(name) and name not in RESERVED_KEYWORD_NAMES


def literal(values: list[Any]) -> str:
    return "Literal[" + ", ".join(json.dumps(value) for value in values) + "]"


def param_type(name: str, metadata: dict[str, Any]) -> str:
    # `value_type` is the fetcher's verdict, and it overrides the playground's widget type.
    if name == "api_key" or metadata.get("value_type") == "string":
        return "str"
    if name in BOOLEAN_PARAM_NAMES or metadata.get("type") == "checkbox":
        return "_Flag"
    if metadata.get("type") == "number" or metadata.get("value_type") == "number":
        return "_Number"
    options = metadata.get("options")
    if isinstance(options, list) and options:
        return literal(options)
    if not (metadata.get("type") or options or metadata.get("value_type")):
        # The playground does not say what these hold, and the SDK sends numbers as text.
        return "_Number" if name in NUMERIC_PARAM_NAMES else "_Scalar"
    return "str"


def load_engines(snapshot_path: Path = SNAPSHOT_PATH) -> list[Engine]:
    snapshot = json.loads(snapshot_path.read_text(encoding="utf-8"))
    raw_engines = snapshot.get("engines") if isinstance(snapshot, dict) else None
    if not isinstance(raw_engines, dict) or not raw_engines:
        raise ValueError(f"{snapshot_path} has no engines")

    engines = []
    prefixes: dict[str, str] = {}
    for name in sorted(raw_engines):
        raw_params = raw_engines[name]
        if not isinstance(raw_params, dict):
            raise ValueError(f"Engine {name!r} parameters are not an object")
        prefix = class_prefix(name)
        if not prefix or prefix in prefixes:
            raise ValueError(f"Engine {name!r} has an empty or duplicate class name {prefix!r}")
        prefixes[prefix] = name

        params = [
            Param(
                param_name,
                param_type(param_name, metadata),
                param_name in REQUIRED_PARAMS.get(name, ()),
            )
            for param_name, metadata in sorted(raw_params.items())
            if param_name not in {"engine", "output"}
        ]
        engine_required = name != DEFAULT_ENGINE
        engines.append(Engine(name, prefix, tuple(params), engine_required))
    if not any(engine.name == "extract" for engine in engines):
        raise ValueError(f"{snapshot_path} has no extract engine")
    return engines


def typed_dict(name: str, params: list[Param]) -> list[str]:
    lines = [f"{name} = TypedDict(", f'    "{name}",', "    {"]
    for param in params:
        wrapper = "Required" if param.required else "NotRequired"
        lines.append(f'        "{param.name}": {wrapper}[{param.typ}],')
    lines.extend(["    },", "    total=False,", ")", ""])
    return lines


def with_output(params: list[Param], *, text: bool) -> list[Param]:
    output = Param("output", TEXT_OUTPUT, True) if text else Param("output", JSON_OUTPUT, False)
    return sorted([*params, output], key=lambda param: param.name)


def engine_dict_params(engine: Engine, *, engine_required: bool) -> list[Param]:
    return [*engine.params, Param("engine", literal([engine.name]), engine_required)]


def build_engine_params_stub(engines: list[Engine]) -> str:
    lines = [
        HEADER,
        "from typing import Union",
        "from typing_extensions import Literal, NotRequired, Required, TypedDict, TypeAlias",
        "",
        '_Flag: TypeAlias = Union[bool, Literal[0, 1, "0", "1", "true", "false"]]',
        "_Number: TypeAlias = Union[int, float, str]",
        "_Scalar: TypeAlias = Union[str, int, float]",
        "",
    ]
    for engine in engines:
        params = engine_dict_params(engine, engine_required=engine.engine_required)
        lines.extend(typed_dict(engine.json_params, with_output(params, text=False)))
        lines.extend(typed_dict(engine.text_params, with_output(params, text=True)))
        lines.append(f"{engine.search_params}: TypeAlias = Union[{engine.json_params}, {engine.text_params}]")
        lines.append("")

    extract = next(engine for engine in engines if engine.name == "extract")
    extract_params = engine_dict_params(extract, engine_required=False)
    lines.extend(typed_dict("ExtractJsonParams", with_output(extract_params, text=False)))
    lines.extend(typed_dict("ExtractTextParams", with_output(extract_params, text=True)))
    lines.append("ExtractParams: TypeAlias = Union[ExtractJsonParams, ExtractTextParams]")
    lines.append("")

    archive = list(ARCHIVE_PARAMS)
    lines.extend(typed_dict("SearchArchiveJsonParams", with_output(archive, text=False)))
    lines.extend(typed_dict("SearchArchiveTextParams", with_output(archive, text=True)))
    lines.append("SearchArchiveParams: TypeAlias = Union[SearchArchiveJsonParams, SearchArchiveTextParams]")
    lines.append("")

    lines.append("SearchParams: TypeAlias = Union[")
    lines.extend(f"    {engine.search_params}," for engine in engines)
    lines.extend(["]", ""])
    return "\n".join(lines)


def request_option_params() -> list[Param]:
    return [Param(name, typ, False) for name, typ in REQUEST_OPTIONS]


def keyword_params(params: list[Param], *, text: bool) -> list[Param] | None:
    if any(param.required and not is_keyword_argument(param.name) for param in params):
        return None
    usable = [
        param
        for param in params
        if is_keyword_argument(param.name) and param.name not in REQUEST_OPTION_NAMES
    ]
    usable = with_output(usable, text=text) + request_option_params()
    return sorted(usable, key=lambda param: (not param.required, param.name))


def overload(function: str, receiver: str | None, params: list[str], return_type: str) -> list[str]:
    lines = ["@overload", f"def {function}("]
    if receiver:
        lines.append(f"    {receiver},")
    lines.extend(f"    {param}," for param in params)
    lines.append(f") -> {return_type}: ...")
    return lines


def keyword_overloads(function: str, receiver: str | None, params: list[Param]) -> list[str]:
    lines: list[str] = []
    for text, return_type in ((True, "str"), (False, "SerpResults")):
        kw_params = keyword_params(params, text=text)
        if kw_params is None:
            continue
        rendered = ["params: None = None", "*"]
        rendered.extend(f"{param.name}: {param.typ}" + ("" if param.required else " = ...") for param in kw_params)
        lines.extend(overload(function, receiver, rendered, return_type))
    return lines


def mapping_overloads(function: str, receiver: str | None, json_type: str, text_type: str) -> list[str]:
    options = ["*"] + [f"{name}: {typ} = ..." for name, typ in REQUEST_OPTIONS]
    lines = overload(function, receiver, [f"params: {text_type}", *options], "str")
    lines.extend(overload(function, receiver, [f"params: {json_type}", *options], "SerpResults"))
    return lines


def fallback_overload(function: str, receiver: str | None, params_type: str) -> list[str]:
    params = f"params: {params_type}"
    # An `output` keyword overrides the mapping, so a literal value determines the result type.
    lines = overload(function, receiver, [params, "*", f"output: {TEXT_OUTPUT}", "**kwargs: Any"], "str")
    lines.extend(overload(function, receiver, [params, "*", f"output: {JSON_OUTPUT}", "**kwargs: Any"], "SerpResults"))
    lines.extend(overload(function, receiver, [params, "**kwargs: Any"], FALLBACK_RETURN))
    return lines


def search_overloads(engines: list[Engine], receiver: str | None) -> list[str]:
    lines: list[str] = []
    for engine in engines:
        lines.extend(mapping_overloads("search", receiver, engine.json_params, engine.text_params))
        lines.extend(keyword_overloads("search", receiver, [*engine.params, Param("engine", literal([engine.name]), True)]))
        if not engine.engine_required:
            lines.extend(keyword_overloads("search", receiver, list(engine.params)))
    lines.extend(fallback_overload("search", receiver, f"Union[SearchParams, {MUTABLE_PARAMS}]"))
    return lines


def extract_overloads(extract: Engine, receiver: str | None) -> list[str]:
    lines = mapping_overloads("extract", receiver, "ExtractJsonParams", "ExtractTextParams")
    lines.extend(keyword_overloads("extract", receiver, list(extract.params)))
    lines.extend(fallback_overload("extract", receiver, "Mapping[str, Any]"))
    return lines


def archive_overloads(receiver: str | None) -> list[str]:
    lines = mapping_overloads("search_archive", receiver, "SearchArchiveJsonParams", "SearchArchiveTextParams")
    lines.extend(keyword_overloads("search_archive", receiver, list(ARCHIVE_PARAMS)))
    lines.extend(fallback_overload("search_archive", receiver, f"Union[SearchArchiveParams, {MUTABLE_PARAMS}]"))
    return lines


def other_functions(receiver: str | None) -> list[str]:
    prefix = f"{receiver}, " if receiver else ""
    options = ", ".join(f"{name}: {typ} = ..." for name, typ in REQUEST_OPTIONS)
    return [
        f"def upload_image({prefix}image: Union[str, PathLike[str], IO[bytes]], *, {options}, **kwargs: Any) -> Dict[str, Any]: ...",
        f"def locations({prefix}params: Optional[{MUTABLE_PARAMS}] = None, **kwargs: Any) -> List[Dict[str, Any]]: ...",
        f"def account({prefix}params: Optional[{MUTABLE_PARAMS}] = None, **kwargs: Any) -> Dict[str, Any]: ...",
    ]


def functions(engines: list[Engine], receiver: str | None) -> list[str]:
    extract = next(engine for engine in engines if engine.name == "extract")
    return [
        *search_overloads(engines, receiver),
        *extract_overloads(extract, receiver),
        *archive_overloads(receiver),
        *other_functions(receiver),
    ]


def build_core_stub(engines: list[Engine]) -> str:
    imported = [name for engine in engines for name in (engine.json_params, engine.text_params)]
    imported += [
        "ExtractJsonParams",
        "ExtractTextParams",
        "SearchArchiveJsonParams",
        "SearchArchiveParams",
        "SearchArchiveTextParams",
        "SearchParams",
        "_Flag",
        "_Number",
        "_Scalar",
    ]
    lines = [
        HEADER,
        "from os import PathLike",
        "from typing import IO, Any, Dict, List, Mapping, MutableMapping, Optional, Union, overload",
        "from typing_extensions import Literal",
        "",
        "from .engine_params import (",
        *(f"    {name}," for name in sorted(imported)),
        ")",
        "from .http import HTTPClient, _Cert, _Proxies, _Timeout, _Verify",
        "from .models import SerpResults",
        "",
        "class Client(HTTPClient):",
        "    DASHBOARD_URL: str",
        "    def __init__(self, *, api_key: Optional[str] = None, timeout: _Timeout = None) -> None: ...",
        "    def __repr__(self) -> str: ...",
    ]
    lines.extend(f"    {line}" for line in functions(engines, "self"))
    lines.append("")
    lines.extend(functions(engines, None))
    lines.append("")
    return "\n".join(lines)


def render(snapshot_path: Path = SNAPSHOT_PATH) -> dict[str, str]:
    engines = load_engines(snapshot_path)
    outputs = {"core.pyi": build_core_stub(engines), "engine_params.pyi": build_engine_params_stub(engines)}
    for name, content in outputs.items():
        ast.parse(content, filename=name)
    return outputs


def write(outputs: dict[str, str], output_dir: Path = OUTPUT_DIR) -> list[Path]:
    written = []
    for name in GENERATED_FILES:
        path = output_dir / name
        if path.exists() and path.read_text(encoding="utf-8") == outputs[name]:
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        # Path.write_text() only accepts `newline` from Python 3.10.
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(outputs[name])
        written.append(path)
    return written


def stale_files(outputs: dict[str, str], output_dir: Path = OUTPUT_DIR) -> list[Path]:
    stale = []
    for name in GENERATED_FILES:
        path = output_dir / name
        if not path.exists() or path.read_text(encoding="utf-8") != outputs[name]:
            stale.append(path)
    return stale


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--snapshot", type=Path, default=SNAPSHOT_PATH)
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    parser.add_argument("--check", action="store_true", help="fail if generated stubs are out of date")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> int:
    args = parse_args(sys.argv[1:] if argv is None else argv)
    outputs = render(args.snapshot)
    if args.check:
        stale = stale_files(outputs, args.output_dir)
        for path in stale:
            print(f"Generated stub is out of date: {path}", file=sys.stderr)
        if stale:
            print("Run `python stubs/tools/generate_stubs.py` and commit the result.", file=sys.stderr)
            return 1
        print("Generated stubs are up to date.")
        return 0
    written = write(outputs, args.output_dir)
    print(f"Wrote {len(written)} generated stub file(s) to {args.output_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
